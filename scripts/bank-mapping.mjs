export function dimsForTag(tag) {
  const keys = TAG_DIMENSIONS[tag];
  if (!keys) return null;
  return keys.map((key) => DIMENSIONS.find((item) => item.key === key).name);
}

export function levelForUnit(unit, tag = null) {
  return levelFor(unit, tag);
}
